/**
 * 이용 가이드 본문 — 도움말 센터 문법(#437).
 *
 * <p>문체 규칙이 있다. **사실만 짧게 끊어 적는다.** 요약 리드·격려 문장·「~하면 돼요」 류의
 * 안심 카피는 넣지 않는다 — 정보 밀도만 낮춘다. 「처음이어도 괜찮아요」 같은 문장이 있던 자리다.
 *
 * <p>🔴 **여기 적힌 값은 전부 코드와 맞아야 한다.** 가이드가 틀리면 분쟁 소지가 된다.
 * 아래 셋은 실제 상수와 대조해 둔 것이라, 상수를 고칠 때 여기도 함께 본다.
 *
 * | 값 | 코드 |
 * | --- | --- |
 * | 결제 기한 48시간 | `PaymentDeadlinePolicy.PAYMENT_WINDOW` |
 * | 자동 구매확정 3일 | `FulfillmentSweeper.CONFIRM_AFTER_DELIVERED` |
 * | 발송 2·3영업일 | `SHIPPING_DEADLINE_BUSINESS_DAYS` · `SHIPPING_AUTO_CANCEL_BUSINESS_DAYS` |
 */

export type GuideDoc = {
  /** URL 조각. `/guide/{id}` */
  id: string;
  title: string;
  /** 목록에 붙는 한 줄 — 제목만으로 안 갈리는 문서를 가른다. */
  desc: string;
  /** 본문 위 리드. 없으면 생략한다 — 억지로 채우지 않는다. */
  lead?: string;
  /** 사실 표 — 「기한이 며칠이더라」로 온 사람이 스크롤하지 않고 답을 얻는 자리. */
  facts?: [string, string][];
  /** 소제목 + 본문. */
  sections: [string, string][];
  /** 등급 스케일 바를 함께 그린다. */
  scale?: boolean;
  /** 필수 촬영 컷. */
  shots?: string[];
  /** 이 문서는 전용 페이지를 갖는다(상태 등급 기준표). */
  standalone?: boolean;
};

