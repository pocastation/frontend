/** 상단 고정을 앞으로, 나머지는 배열 순서(최신순) 그대로. */
export const ORDERED_NOTICES: Notice[] = [
  ...NOTICES.filter((n) => n.pinned),
  ...NOTICES.filter((n) => !n.pinned),
];

export function findNotice(slug: string): Notice | undefined {
  return NOTICES.find((n) => n.slug === slug);
}
